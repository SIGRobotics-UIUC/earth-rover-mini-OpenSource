    def connect_to_rover(self, ip, port):
        # socket structure:
        sock = socket.create_connection((ip, port))  # make sure Rover IP and port aligns with tcp_bridge
        sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        return sock

